/**
 * Standard Application Error Codes.
 * Aligns with DOC-ENG-004 (API & Server Action Standards).
 */

import { HTTP_STATUS, type HttpStatusCode } from '@/config/constants';

export const ERROR_CODES = {
  // 400 Bad Request / Validation
  VALIDATION_ERROR: 'VALIDATION_ERROR',
  BAD_REQUEST: 'BAD_REQUEST',

  // 401 Unauthorized
  UNAUTHORIZED: 'UNAUTHORIZED',

  // 403 Forbidden
  FORBIDDEN: 'FORBIDDEN',

  // 404 Not Found
  NOT_FOUND: 'NOT_FOUND',

  // 405 Method Not Allowed
  METHOD_NOT_ALLOWED: 'METHOD_NOT_ALLOWED',

  // 409 Conflict (Unique constraint violation)
  CONFLICT: 'CONFLICT',

  // 422 Business Invariant / Unprocessable
  BUSINESS_RULE_VIOLATION: 'BUSINESS_RULE_VIOLATION',

  // 429 Rate Limit
  RATE_LIMIT_EXCEEDED: 'RATE_LIMIT_EXCEEDED',

  // 500 Internal / System Errors
  INTERNAL_ERROR: 'INTERNAL_ERROR',
  DATABASE_ERROR: 'DATABASE_ERROR',

  // 502 / 503 Third-Party Services
  EXTERNAL_SERVICE_ERROR: 'EXTERNAL_SERVICE_ERROR',
} as const;

export type ErrorCode = (typeof ERROR_CODES)[keyof typeof ERROR_CODES];

/**
 * Maps each standard ErrorCode to its authoritative HTTP status code.
 */
export const ERROR_CODE_TO_HTTP_STATUS: Record<ErrorCode, HttpStatusCode> = {
  [ERROR_CODES.VALIDATION_ERROR]: HTTP_STATUS.BAD_REQUEST,
  [ERROR_CODES.BAD_REQUEST]: HTTP_STATUS.BAD_REQUEST,
  [ERROR_CODES.UNAUTHORIZED]: HTTP_STATUS.UNAUTHORIZED,
  [ERROR_CODES.FORBIDDEN]: HTTP_STATUS.FORBIDDEN,
  [ERROR_CODES.NOT_FOUND]: HTTP_STATUS.NOT_FOUND,
  [ERROR_CODES.METHOD_NOT_ALLOWED]: HTTP_STATUS.METHOD_NOT_ALLOWED,
  [ERROR_CODES.CONFLICT]: HTTP_STATUS.CONFLICT,
  [ERROR_CODES.BUSINESS_RULE_VIOLATION]: HTTP_STATUS.UNPROCESSABLE_ENTITY,
  [ERROR_CODES.RATE_LIMIT_EXCEEDED]: HTTP_STATUS.TOO_MANY_REQUESTS,
  [ERROR_CODES.INTERNAL_ERROR]: HTTP_STATUS.INTERNAL_SERVER_ERROR,
  [ERROR_CODES.DATABASE_ERROR]: HTTP_STATUS.INTERNAL_SERVER_ERROR,
  [ERROR_CODES.EXTERNAL_SERVICE_ERROR]: HTTP_STATUS.BAD_GATEWAY,
};
